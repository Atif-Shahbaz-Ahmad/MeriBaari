export function getServiceById(id: string): QueueService | undefined {
  return MOCK_SERVICES.find((service) => service.id === id);
}

export function getServicesByDepartment(departmentId: string): QueueService[] {
  return MOCK_SERVICES.filter((service) => service.departmentId === departmentId);
}

export function getServicesByIds(ids: string[]): QueueService[] {
  return ids
    .map((id) => getServiceById(id))
    .filter((service): service is QueueService => Boolean(service));
}
