export function getOrganizationById(id: string): Organization | undefined {
  return MOCK_ORGANIZATIONS.find((org) => org.id === id);
}

export function searchOrganizations(
  query: string,
  category: OrganizationCategory | 'all' = 'all',
): Organization[] {
  const normalized = query.trim().toLowerCase();

  return MOCK_ORGANIZATIONS.filter((org) => {
    const matchesCategory = category === 'all' || org.category === category;
    if (!matchesCategory) return false;
    if (!normalized) return true;

    return (
      org.name.toLowerCase().includes(normalized) ||
      org.city.toLowerCase().includes(normalized) ||
      org.address.toLowerCase().includes(normalized) ||
      org.category.toLowerCase().includes(normalized)
    );
  });
}

